// The photo reader client (photo-reader.js) against a fake llama-server on a spare port.
// Runs standalone, no server needed. Usage: node service/src/__tests__/photo-reader.test.js

import http from 'node:http';
import { modelFiles, photoReaderArgs, describeWithPhotoReader, PHOTO_READER_PORT } from '../photo-reader.js';

let passed = 0;
let failed = 0;
async function test(name, fn) {
  try {
    await fn();
    passed++;
    console.log(`  ✓ ${name}`);
  } catch (err) {
    failed++;
    console.log(`  ✗ ${name}: ${err.message}`);
  }
}
function eq(a, b, what) {
  if (JSON.stringify(a) !== JSON.stringify(b)) throw new Error(`${what}: got ${JSON.stringify(a)}, want ${JSON.stringify(b)}`);
}

// A fake llama-server: /props as the real one answers it, /completion records what it was sent.
function fakeServer(props, completion = { status: 200, body: { content: ' A black dog on a mat. ', timings: { prompt_n: 753, predicted_n: 9 } } }) {
  const seen = [];
  const server = http.createServer((req, res) => {
    let body = '';
    req.on('data', (c) => { body += c; });
    req.on('end', () => {
      seen.push({ path: req.url, body: body ? JSON.parse(body) : null });
      const [status, out] = req.url === '/props' ? [200, props] : [completion.status, completion.body];
      res.writeHead(status, { 'Content-Type': 'application/json' });
      res.end(JSON.stringify(out));
    });
  });
  return new Promise((resolve) => server.listen(0, '127.0.0.1', () => resolve({ port: server.address().port, seen, close: () => server.close() })));
}
const MOONDREAM = { model_alias: 'moondream:latest', modalities: { vision: true, audio: false }, media_marker: '<__media_abc__>' };

console.log('photo-reader');

await test('modelFiles takes the model, then the projector, from the modelfile', () => {
  const mf = '# Modelfile generated by "ollama show"\nFROM C:\\b\\sha256-text\nFROM C:\\b\\sha256-proj\nTEMPLATE "{{ .Prompt }}"\nPARAMETER stop Question:\n';
  eq(modelFiles(mf), { file: 'C:\\b\\sha256-text', projector: 'C:\\b\\sha256-proj' }, 'files');
  eq(modelFiles('FROM C:\\b\\sha256-text\n'), null, 'a model without a projector');
  eq(modelFiles(undefined), null, 'no modelfile');
});

await test('the steward starts it on the graphics chip, under the model name', () => {
  const a = photoReaderArgs({ file: 'T', projector: 'P', model: 'moondream:latest' });
  eq(a.slice(0, 4), ['--model', 'T', '--mmproj', 'P'], 'files');
  eq(a[a.indexOf('--alias') + 1], 'moondream:latest', 'alias');
  eq(a[a.indexOf('--port') + 1], String(PHOTO_READER_PORT), 'port');
  eq(a[a.indexOf('-ngl') + 1], '99', 'layers on the chip');
});

await test('nothing running: null, so the caller asks Ollama', async () => {
  const s = await fakeServer(MOONDREAM);
  const port = s.port;
  s.close();
  await new Promise((r) => setTimeout(r, 50));
  eq(await describeWithPhotoReader('Describe.', 'IMG', { model: 'moondream', port }), null, 'result');
});

await test('describes with the marker it was given, in moondream\'s template', async () => {
  const s = await fakeServer(MOONDREAM);
  try {
    const r = await describeWithPhotoReader('Describe this image.', 'IMG64', { model: 'moondream', maxTokens: 64, port: s.port });
    eq(r, { text: 'A black dog on a mat.', input_tokens: 753, output_tokens: 9 }, 'result');
    const sent = s.seen.find((x) => x.path === '/completion').body;
    eq(sent.prompt, { prompt_string: '<__media_abc__> Question: Describe this image.\n\n Answer:', multimodal_data: ['IMG64'] }, 'prompt');
    eq([sent.n_predict, sent.temperature, sent.stop.includes('Question:'), sent.cache_prompt], [64, 0, true, false], 'settings');
  } finally { s.close(); }
});

await test('another model, or one that cannot see: null and nothing sent', async () => {
  const s = await fakeServer(MOONDREAM);
  const blind = await fakeServer({ ...MOONDREAM, modalities: { vision: false } });
  try {
    eq(await describeWithPhotoReader('Describe.', 'IMG', { model: 'llava-phi3', port: s.port }), null, 'other model');
    eq(await describeWithPhotoReader('Describe.', 'IMG', { model: 'moondream:latest', port: blind.port }), null, 'no vision');
    eq(s.seen.concat(blind.seen).filter((x) => x.path === '/completion').length, 0, 'completions sent');
  } finally { s.close(); blind.close(); }
});

await test('a failing reader throws, so the caller logs it and asks Ollama', async () => {
  const s = await fakeServer(MOONDREAM, { status: 400, body: { error: { message: 'Failed to tokenize prompt' } } });
  try {
    let err = null;
    try { await describeWithPhotoReader('Describe.', 'IMG', { model: 'moondream', port: s.port }); } catch (e) { err = e; }
    if (!err || !/photo reader 400/.test(err.message)) throw new Error(`want a 400 error, got ${err?.message}`);
  } finally { s.close(); }
});

console.log(`\n${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
